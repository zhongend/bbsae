/**
 * Full-screen effect library: a thumbnail grid with categories, search and animated tiles.
 *
 * <p>The left panel is a compact list; this is the reference-style browser. Every tile carries a
 * rendered preview from {@code assets/bbsae/textures/effects/}, generated by the headless
 * {@code EffectThumbnailTest}, so the picture in the grid is the effect applied to the same test card
 * that the contact sheet uses. Clicking a tile applies the effect to the selected layer; the panel
 * stays open so several effects can be stacked.</p>
 */
public class UIEffectLibraryOverlay extends UIElement
{
    private static final int TILE_W = 132;
    private static final int TILE_H = 118;
    private static final int TILE_GAP = 8;
    private static final int PAD = 14;

    private final UICompositorPanel panel;
    private final Runnable onClose;

    private final UILabel title;
    private final UILabel hint;
    private final UILabel status;
    private final UITextbox search;
    private final UIIcon close;
    private final Chips chips;
    private final Grid grid;

    private final UiMotion motion = new UiMotion();

    private final List<CompEffectRegistry.Definition> all = new ArrayList<>();
    private final List<CompEffectRegistry.Definition> filtered = new ArrayList<>();
    private final List<String> categories = new ArrayList<>();

    private String category = "全部";
    private String query = "";
    private String appliedId = "";
    private long appliedAt;
    private int laidOutWidth = -1;
    private int laidOutHeight = -1;

    private final UIElement box;

    public UIEffectLibraryOverlay(UICompositorPanel panel, Runnable onClose)
    {
        this.panel = panel;
        this.onClose = onClose;

        this.collectDefinitions();

        this.box = new UIElement()
        {
            @Override
            public void render(UIContext context)
            {
                context.batcher.box(this.area.x, this.area.y, this.area.ex(), this.area.ey(), 0xFF12161C);
                context.batcher.outline(this.area.x, this.area.y, this.area.ex(), this.area.ey(), 0xFF36414F);
                super.render(context);
            }

            @Override
            protected boolean subMouseClicked(UIContext context)
            {
                return this.area.isInside(context);
            }
        };

        this.box.relative(this).x(0).y(0);

        this.title = new UILabel(IKey.constant("效果库"));
        this.hint = new UILabel(IKey.constant("单击应用到当前轨道；可连续叠加多个效果"));
        this.hint.color(0xFF8A94A6, false);

        this.status = new UILabel(IKey.constant(""));
        this.status.color(0xFF9AA6B8, false);

        this.search = new UITextbox(64, (text) ->
        {
            this.query = text == null ? "" : text.trim().toLowerCase(Locale.ROOT);
            this.rebuild();
        });
        this.search.placeholder(IKey.constant("搜索效果…"));

        this.close = new UIIcon(Icons.CLOSE, (icon) -> this.onClose.run());

        this.chips = new Chips();
        this.grid = new Grid();

        this.box.add(this.title, this.hint, this.search, this.close, this.chips, this.grid, this.status);
        this.add(this.box);

        this.rebuild();
    }

    private void collectDefinitions()
    {
        Set<String> seen = new LinkedHashSet<>();

        seen.add("全部");

        for (CompEffectRegistry.Definition definition : CompEffectRegistry.all())
        {
            if (CompEffectRegistry.isLibraryHidden(definition.id))
            {
                continue;
            }

            this.all.add(definition);
            seen.add(definition.category == null || definition.category.isBlank() ? "其他" : definition.category);
        }

        this.categories.addAll(seen);

        /* Pinned on top once the panel has any history; it is rebuilt from the same registry
         * definitions, so favourites cannot point at a removed effect. */
        if (this.categories.contains("最近使用") == false)
        {
            this.categories.add(1, "最近使用");
        }
    }

    private void rebuild()
    {
        this.filtered.clear();

        boolean recent = "最近使用".equals(this.category);

        if (recent)
        {
            for (String id : this.panel.getRecentEffects())
            {
                for (CompEffectRegistry.Definition definition : this.all)
                {
                    if (definition.id.equals(id))
                    {
                        this.filtered.add(definition);

                        break;
                    }
                }
            }

            this.updateStatus();
            this.grid.scrollToTop();

            return;
        }

        for (CompEffectRegistry.Definition definition : this.all)
        {
            String category = definition.category == null || definition.category.isBlank() ? "其他" : definition.category;

            if (!"全部".equals(this.category) && !category.equals(this.category))
            {
                continue;
            }

            if (!this.query.isEmpty())
            {
                String haystack = (definition.name + " " + definition.id + " " + category).toLowerCase(Locale.ROOT);

                if (!haystack.contains(this.query))
                {
                    continue;
                }
            }

            this.filtered.add(definition);
        }

        if (this.grid != null)
        {
            this.grid.scrollToTop();
        }

        this.updateStatus();
    }

    private void updateStatus()
    {
        if (this.status == null)
        {
            return;
        }

        String suffix = this.query.isEmpty() ? "" : "（搜索：" + this.query + "）";

        this.status.label = IKey.constant(this.filtered.size() + " 个效果 · " + this.category + suffix);
    }

    @Override
    public void render(UIContext context)
    {
        this.layout();

        this.motion.tickFrame();

        InterfaceBlur.applyUnder();
        context.batcher.box(this.area.x, this.area.y, this.area.ex(), this.area.ey(), 0x66000000);
        super.render(context);
    }

    private void layout()
    {
        int width = this.area.w;
        int height = this.area.h;

        if (width == this.laidOutWidth && height == this.laidOutHeight)
        {
            return;
        }

        this.laidOutWidth = width;
        this.laidOutHeight = height;

        int marginX = Math.max(24, Math.min(90, width / 12));
        int marginY = Math.max(20, Math.min(70, height / 14));
        int boxWidth = Math.max(320, width - marginX * 2);
        int boxHeight = Math.max(260, height - marginY * 2);

        this.box.relative(this).x(marginX).y(marginY).w(boxWidth).h(boxHeight);

        int innerLeft = PAD;
        int innerRight = boxWidth - PAD;

        this.title.relative(this.box).x(innerLeft).y(9).w(160).h(16);
        this.hint.relative(this.box).x(innerLeft).y(26).w(360).h(12);
        this.close.relative(this.box).x(innerRight - 18).y(8).w(18).h(18);
        this.search.relative(this.box).x(innerRight - 18 - 8 - 240).y(8).w(240).h(18);
        this.chips.relative(this.box).x(innerLeft).y(42).w(boxWidth - PAD * 2).h(22);
        this.status.relative(this.box).x(innerLeft).y(boxHeight - 18).w(boxWidth - PAD * 2).h(12);
        this.grid.relative(this.box).x(innerLeft).y(70).w(boxWidth - PAD * 2).h(boxHeight - 70 - 24);

        this.resize();
    }

    @Override
    protected boolean subKeyPressed(UIContext context)
    {
        if (context.getKeyAction() == KeyAction.PRESSED && context.getKeyCode() == GLFW.GLFW_KEY_ESCAPE)
        {
            this.onClose.run();

            return true;
        }

        return super.subKeyPressed(context);
    }

    private void apply(CompEffectRegistry.Definition definition)
    {
        this.panel.applyEffect(definition.id);
        this.appliedId = definition.id;
        this.appliedAt = System.currentTimeMillis();
        this.status.label = IKey.constant("已应用：" + definition.name);
    }

    /** Category buttons; a single scrollable row, laid out from the strip width. */
    private final class Chips extends UIElement
    {
        private int scroll;

        @Override
        public void render(UIContext context)
        {
            context.batcher.clip(this.area, context);

            try
            {
                int x = this.area.x - this.scroll;
                int width = this.area.w;

                for (String label : UIEffectLibraryOverlay.this.categories)
                {
                    int chipWidth = 20 + label.length() * 12;
                    boolean active = label.equals(UIEffectLibraryOverlay.this.category);
                    boolean hover = context.mouseX >= x && context.mouseX <= x + chipWidth
                        && this.area.isInside(context);
                    float amount = UIEffectLibraryOverlay.this.motion.hover("chip:" + label, hover ? "hot" : null);
                    int fill = UiMotion.lerpColor(0xFF20262F, 0xFF2A3442, amount);

                    if (active)
                    {
                        fill = 0xFF2F5C9E;
                    }

                    context.batcher.box(x, this.area.y, x + chipWidth, this.area.ey(), fill);
                    context.batcher.text(label, x + 6, this.area.y + 7, active ? 0xFFFFFFFF : 0xFFB8C4D6);
                    x += chipWidth + 4;
                }
            }
            finally
            {
                context.batcher.unclip(context);
            }
        }

        @Override
        protected boolean subMouseClicked(UIContext context)
        {
            if (context.mouseButton != 0 || !this.area.isInside(context))
            {
                return super.subMouseClicked(context);
            }

            int x = this.area.x - this.scroll;

            for (String label : UIEffectLibraryOverlay.this.categories)
            {
                int chipWidth = 20 + label.length() * 12;

                if (context.mouseX >= x && context.mouseX <= x + chipWidth)
                {
                    UIEffectLibraryOverlay.this.category = label;
                    UIEffectLibraryOverlay.this.rebuild();

                    return true;
                }

                x += chipWidth + 4;
            }

            return true;
        }

        @Override
        protected boolean subMouseScrolled(UIContext context)
        {
            if (!this.area.isInside(context))
            {
                return super.subMouseScrolled(context);
            }

            int total = 0;

            for (String label : UIEffectLibraryOverlay.this.categories)
            {
                total += 20 + label.length() * 12 + 4;
            }

            this.scroll = Math.max(0, Math.min(Math.max(0, total - this.area.w),
                this.scroll - (int) Math.round(context.mouseWheel * 40D)));

            return true;
        }
    }

    /** The thumbnail grid: smooth scroll, hover lift, selection pulse and staggered entrance. */
    private final class Grid extends UIElement
    {
        private int scrollY;
        private float scrollSmooth;
        private boolean smoothReady;
        private String hot;
        private int pressY = Integer.MIN_VALUE;
        private int pressScroll;

        void scrollToTop()
        {
            this.scrollY = 0;
            this.scrollSmooth = 0F;
        }

        private int columns()
        {
            return Math.max(1, (this.area.w + TILE_GAP) / (TILE_W + TILE_GAP));
        }

        private int rows()
        {
            return (UIEffectLibraryOverlay.this.filtered.size() + this.columns() - 1) / this.columns();
        }

        private int contentHeight()
        {
            return Math.max(0, this.rows() * (TILE_H + TILE_GAP) - TILE_GAP);
        }

        private int maxScroll()
        {
            return Math.max(0, this.contentHeight() - this.area.h);
        }

        private void clamp()
        {
            this.scrollY = Math.max(0, Math.min(this.maxScroll(), this.scrollY));
        }

        private int indexAt(int mouseX, int mouseY)
        {
            if (!this.area.isInside(mouseX, mouseY))
            {
                return -1;
            }

            int column = (mouseX - this.area.x) / (TILE_W + TILE_GAP);
            int row = (mouseY - this.area.y + Math.round(this.scrollSmooth)) / (TILE_H + TILE_GAP);

            if (column < 0 || column >= this.columns() || row < 0)
            {
                return -1;
            }

            int index = row * this.columns() + column;

            return index >= 0 && index < UIEffectLibraryOverlay.this.filtered.size() ? index : -1;
        }

        @Override
        public void render(UIContext context)
        {
            if (!this.smoothReady)
            {
                this.scrollSmooth = this.scrollY;
                this.smoothReady = true;
            }

            this.scrollSmooth = CompPrefs.animating()
                ? UiMotion.approach(this.scrollSmooth, this.scrollY, 18F * CompPrefs.speed(), UIEffectLibraryOverlay.this.motion.dt)
                : this.scrollY;

            int hotIndex = this.indexAt(context.mouseX, context.mouseY);

            this.hot = hotIndex >= 0 ? "tile:" + hotIndex : null;

            if (this.pressY != Integer.MIN_VALUE)
            {
                int delta = this.pressY - context.mouseY;

                if (Math.abs(delta) > 4)
                {
                    this.scrollY = this.pressScroll + delta;
                    this.clamp();
                }
            }

            context.batcher.box(this.area.x, this.area.y, this.area.ex(), this.area.ey(), 0xFF141920);
            context.batcher.clip(this.area, context);

            try
            {
                int columns = this.columns();
                int scroll = Math.round(this.scrollSmooth);
                int firstRow = Math.max(0, scroll / (TILE_H + TILE_GAP));
                int lastRow = (scroll + this.area.h) / (TILE_H + TILE_GAP);

                for (int row = firstRow; row <= lastRow; row++)
                {
                    for (int column = 0; column < columns; column++)
                    {
                        int index = row * columns + column;

                        if (index >= UIEffectLibraryOverlay.this.filtered.size())
                        {
                            break;
                        }

                        this.renderTile(context, UIEffectLibraryOverlay.this.filtered.get(index), index,
                            this.area.x + column * (TILE_W + TILE_GAP),
                            this.area.y + row * (TILE_H + TILE_GAP) - scroll);
                    }
                }
            }
            finally
            {
                context.batcher.unclip(context);
            }

            if (UIEffectLibraryOverlay.this.filtered.isEmpty())
            {
                context.batcher.text("没有匹配的效果", this.area.x + 8, this.area.y + 8, 0xFF8A94A6);
            }
        }

        private void renderTile(UIContext context, CompEffectRegistry.Definition definition, int index, int x, int y)
        {
            String key = "tile:" + index;
            boolean hovered = key.equals(this.hot);
            float hover = UIEffectLibraryOverlay.this.motion.hover(key, this.hot);
            float intro = UIEffectLibraryOverlay.this.motion.intro(Math.min(0.36F, index * 0.004F));
            float pulse = definition.id.equals(UIEffectLibraryOverlay.this.appliedId)
                ? Math.max(0F, 1F - (System.currentTimeMillis() - UIEffectLibraryOverlay.this.appliedAt) / 380F)
                : 0F;
            int drawY = y + Math.round((1F - intro) * 9F * UIEffectLibraryOverlay.this.motion.intensity());
            float lift = hover * 3F * UIEffectLibraryOverlay.this.motion.intensity();
            int ty = drawY - Math.round(lift);
            int fill = UiMotion.lerpColor(0xFF20262F, 0xFF2C3A4E, hover);

            fill = UiMotion.lerpColor(fill, 0xFF2F5C9E, pulse);

            if (hover > 0.01F && CompPrefs.get().shadows)
            {
                UiGfx.shadow(context.batcher, x, ty, TILE_W, TILE_H, 4F,
                    UiGfx.alpha(0xFF000000, 0.18F * hover * UIEffectLibraryOverlay.this.motion.intensity()));
            }

            context.batcher.box(x, ty, x + TILE_W, ty + TILE_H, UiGfx.mulA(fill, intro));

            if (hover > 0.01F || pulse > 0.01F)
            {
                UiGfx.accentRail(context.batcher, x, ty + 1, TILE_H - 2,
                    Math.max(hover, pulse) * intro, 0xFF4C86D8);
            }

            int thumbSize = 74;
            int thumbX = x + (TILE_W - thumbSize) / 2;
            int thumbY = ty + 8;
            ImageTextureCache.Entry texture = ImageTextureCache.get("bbsae", "bbsae:textures/effects/" + definition.id + ".png");

            if (texture != null)
            {
                float fit = Math.min(thumbSize / (float) texture.width, thumbSize / (float) texture.height);
                int dw = Math.max(1, Math.round(texture.width * fit));
                int dh = Math.max(1, Math.round(texture.height * fit));

                context.batcher.texturedBox(texture.texture.id, UiGfx.mulA(0xFFFFFFFF, intro),
                    thumbX + (thumbSize - dw) / 2, thumbY + (thumbSize - dh) / 2, dw, dh,
                    0F, 0F, texture.width, texture.height, texture.width, texture.height);
            }
            else
            {
                Icon icon = EffectIcons.forDefinition(definition);

                context.batcher.icon(icon == null ? Icons.NONE : icon, UiGfx.mulA(0xFF66707E, intro),
                    thumbX + thumbSize / 2 - 8, thumbY + thumbSize / 2 - 8);
            }

            String name = definition.name;
            int labelColor = UiGfx.mulA(0xFFE8EDF5, intro);

            context.batcher.text(name, x + 7, ty + TILE_H - 28, labelColor);
            context.batcher.text(definition.category == null ? "" : definition.category,
                x + 7, ty + TILE_H - 15, UiGfx.mulA(0xFF7E8B9E, intro));
        }

        @Override
        protected boolean subMouseClicked(UIContext context)
        {
            if (context.mouseButton != 0 || !this.area.isInside(context))
            {
                return super.subMouseClicked(context);
            }

            int index = this.indexAt(context.mouseX, context.mouseY);

            if (index >= 0)
            {
                UIEffectLibraryOverlay.this.apply(UIEffectLibraryOverlay.this.filtered.get(index));

                return true;
            }

            this.pressY = context.mouseY;
            this.pressScroll = this.scrollY;
            this.smoothReady = true;

            return true;
        }

        @Override
        protected boolean subMouseReleased(UIContext context)
        {
            this.pressY = Integer.MIN_VALUE;

            return super.subMouseReleased(context);
        }

        @Override
        protected boolean subMouseScrolled(UIContext context)
        {
            if (!this.area.isInside(context))
            {
                return super.subMouseScrolled(context);
            }

            this.scrollY -= (int) Math.round(context.mouseWheel * 48D);
            this.clamp();

            return true;
        }
    }

}
